package com.infineonbit.sustainablefarm.modules.producttransformation.harvestevent.model;
import com.infineonbit.sustainablefarm.modules.producttransformation.batch.model.Batch;

import com.fasterxml.jackson.annotation.JsonCreator;
import jakarta.persistence.*;
import org.hibernate.annotations.GenericGenerator;
import lombok.AllArgsConstructor;
import lombok.EqualsAndHashCode;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import lombok.ToString;
import java.time.LocalDate;
import java.time.LocalTime;
import java.math.BigDecimal;

/**
 * HarvestEvent Entity
 * Harvest data from Plants workstream - Integration Entity
 * 
 * Business Rule: Batch ID generated by Plants system
 * Business Rule: One harvest event creates exactly one batch
 * 
 * Architecture Note: 
 * - batch_id is stored as VARCHAR without explicit database FK constraint
 * - This is intentional for Plants workstream integration
 * - Relationship to Batch is maintained through batch_id field value
 * - Per MCD: "HARVEST_EVENT '1' -- '1' BATCH : creates_batch"
 * 
 * @author Abdoul Ben Fatao SANON
 * @version 1.0.0
 */
@Entity
@Table(name = "harvest_event")
@Getter
@Setter
@EqualsAndHashCode
@ToString
@NoArgsConstructor
@AllArgsConstructor
public class HarvestEvent {

    @Id
    @GeneratedValue(generator = "assigned")
    @GenericGenerator(name = "assigned", strategy = "assigned")
    @Column(name = "harvest_id", length = 50)
    private String harvestId;

    // Reference to Plants harvest ID for cross-module integration
    // Allows Product Transformation to reference Plants harvest data without duplication
    @Column(name = "plants_harvest_id")
    private Long plantsHarvestId;

    /**
     * Lot number assigned by Plants (for example {@code LOT-2026-A-001}).
     *
     * <p>Stored as its own field, not reused as {@code batchId}: a harvest lot and
     * a transformation lot are not always the same thing (one harvest can be split
     * into several drying lots, and several harvests can be merged into one
     * transformation lot). Keeping both lets a transformation lot be traced back
     * to the farm harvest it came from.
     */
    @Column(name = "lot_number", length = 50)
    private String lotNumber;

    @Column(name = "batch_id", nullable = false, unique = true, length = 50)
    private String batchId;

    // Note: No @OneToOne relationship to Batch entity
    // Reason: Database schema has batch_id as VARCHAR foreign key without explicit FK constraint
    // Relationship is maintained through batch_id field for Plants integration
    // Per MCD: "HARVEST_EVENT '1' -- '1' BATCH : creates_batch"

    @Column(name = "harvest_date", nullable = false)
    private LocalDate harvestDate;

    @Column(name = "harvest_time")
    private LocalTime harvestTime;

    @Enumerated(EnumType.STRING)
    @Column(name = "mango_variety", nullable = false, length = 20)
    private MangoVariety mangoVariety;

    /**
     * Farm identifier of the harvest.
     *
     * <p>Optional because the Plants module has a single farm and does not record
     * an identifier: an imported harvest therefore arrives without one. The
     * common cross-module farm identifier is still to be agreed, so a null value
     * means "not assigned yet", not "unknown". A harvest created through the
     * Product Transformation API still validates it as required.
     */
    @Column(name = "farm_id", length = 50)
    private String farmId;

    @Column(name = "block_id", nullable = false, length = 50)
    private String blockId;

    @Column(name = "harvest_quantity_kg", nullable = false, precision = 10, scale = 2)
    private BigDecimal harvestQuantityKg;

    @Enumerated(EnumType.STRING)
    @Column(name = "quality_grade", nullable = false, length = 1)
    private QualityGrade qualityGrade;

    @Column(name = "quality_grade_description", length = 200)
    private String qualityGradeDescription;

    @Column(name = "harvest_team_id", length = 50)
    private String harvestTeamId;

    @Column(name = "harvest_supervisor", length = 100)
    private String harvestSupervisor;

    @Column(name = "weather_conditions", length = 200)
    private String weatherConditions;

    @Column(name = "storage_location", length = 50)
    private String storageLocation;

    @Column(name = "created_at", updatable = false)
    private java.sql.Timestamp createdAt;

    @Column(name = "updated_at")
    private java.sql.Timestamp updatedAt;

    @PrePersist
    protected void onCreate() {
        createdAt = new java.sql.Timestamp(System.currentTimeMillis());
        updatedAt = new java.sql.Timestamp(System.currentTimeMillis());
    }

    @PreUpdate
    protected void onUpdate() {
        updatedAt = new java.sql.Timestamp(System.currentTimeMillis());
    }

    /**
     * Mango Variety Enum
     * Business Rule: Matches database CHECK constraint
     */
    public enum MangoVariety {
        KEITT,
        KENT,
        TOMMY,
        AMÉLIE,
        OTHER;

        /**
         * Resolve a variety name coming from the Plants module (for example
         * {@code "Keitt"}, {@code "keitt"} or {@code "Amelie"}) to this enum.
         *
         * <p>Plants returns the planted name as stored, so it can differ in case
         * and accents from the enum constants ({@code KEITT}, {@code AMÉLIE}).
         * The comparison is therefore case-insensitive and accent-insensitive.
         * Unknown or missing names map to {@link #OTHER} instead of failing the
         * whole harvest import.
         */
        public static MangoVariety fromPlants(String varietyName) {
            String normalized = normalize(varietyName);
            if (normalized == null) {
                return OTHER;
            }
            switch (normalized) {
                case "KEITT":
                    return KEITT;
                case "KENT":
                    return KENT;
                case "TOMMY":
                case "TOMMY ATKINS":
                    return TOMMY;
                case "AMELIE":
                    return AMÉLIE;
                case "OTHER":
                    return OTHER;
                default:
                    return OTHER;
            }
        }

        /**
         * Bind a variety name coming from an HTTP payload.
         *
         * <p>Unlike {@link #fromPlants(String)} this creator is strict: a client
         * that writes {@code "Alphonso"} gets a {@code 400}, not a silent
         * {@link #OTHER}. The lenient path exists for data owned by Plants, where
         * refusing a whole harvest over an unmapped variety would be worse than
         * keeping the record with {@code OTHER}. Accepting case and accents here
         * is what lets Plants' usual spelling ({@code "Keitt"}, {@code "Amélie"})
         * be posted directly to the Product Transformation API.
         *
         * @param varietyName variety name as written by the client
         * @return the matching constant
         * @throws IllegalArgumentException when the name is not a known variety
         */
        @JsonCreator
        public static MangoVariety fromJson(String varietyName) {
            String normalized = normalize(varietyName);
            if (normalized == null) {
                return null;
            }
            switch (normalized) {
                case "KEITT":
                    return KEITT;
                case "KENT":
                    return KENT;
                case "TOMMY":
                case "TOMMY ATKINS":
                    return TOMMY;
                case "AMELIE":
                    return AMÉLIE;
                case "OTHER":
                    return OTHER;
                default:
                    throw new IllegalArgumentException(
                            "Unknown mango variety: '" + varietyName
                                    + "'. Expected one of KEITT, KENT, TOMMY, AMÉLIE, OTHER");
            }
        }

        private static String normalize(String varietyName) {
            if (varietyName == null) {
                return null;
            }
            return java.text.Normalizer.normalize(varietyName.trim(), java.text.Normalizer.Form.NFD)
                    .replaceAll("\\p{M}", "")
                    .toUpperCase(java.util.Locale.ROOT);
        }
    }

    /**
     * Quality Grade Enum
     * Business Rule: Matches database CHECK constraint
     */
    public enum QualityGrade {
        A,    // Premium - No defects
        B,    // Standard - Minor defects
        C,    // Processing - Visible defects
        D     // Reject - Significant defects
    }
}