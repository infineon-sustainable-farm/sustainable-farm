package com.infineonbit.sustainablefarm.modules.producttransformation.integration.cropstorage.service;

import com.infineonbit.sustainablefarm.modules.producttransformation.integration.cropstorage.dto.CropStorageEntryRequest;
import com.infineonbit.sustainablefarm.modules.producttransformation.integration.cropstorage.dto.CropStorageEntryResponse;
import org.springframework.stereotype.Service;

import java.util.Optional;

/**
 * Crop Storage Integration Service
 * Storage entry handoff from Product Transformation to Crop Storage
 *
 * Contract from Crop Storage team:
 * Convention: snake_case
 * Endpoint: /api/crop-storage/entries (or /api/storage-entries - to be decided)
 * Error handling: 409 on capacity overflow
 * batch_code generated by Crop Storage (B26-01 format)
 *
 * <p>The Crop Storage module is not built yet (docs/adr/0003-communication-entre-modules.md):
 * no module receives a storage entry. This service used to POST the entry over HTTP to
 * {@code /api/crop-storage/entries} of the application itself, that is to the controller that
 * called it, which called it again until the read timeout ended the loop with a 500 error.
 * It now fails at once with the same error, without the call: no entry is ever created.
 *
 * @author Abdoul Ben Fatao SANON
 * @version 1.2.0
 */
@Service
public class CropStorageIntegrationService {

    /**
     * Create a storage entry in Crop Storage module
     * Used when batch reaches COMPLETED status and needs to be stored
     *
     * @param request Storage entry request
     * @return never: no module receives a storage entry yet
     * @throws IllegalStateException always, answered as a 500 error, until Crop Storage exists
     */
    public CropStorageEntryResponse createStorageEntry(CropStorageEntryRequest request) {
        throw new IllegalStateException("Crop Storage is not available: no storage entry was created for batch "
                + (request == null ? null : request.getBatchId()));
    }

    /**
     * Check whether Crop Storage would accept the entry.
     *
     * <p>A capacity check must not write: creating the entry to probe capacity persisted a
     * real storage entry on every call, which is not idempotent and pollutes Crop Storage.
     * Crop Storage has not published a dedicated capacity endpoint yet, so this method
     * never calls {@link #createStorageEntry(CropStorageEntryRequest)} and reports the
     * gap instead of guessing: an empty result means "capacity unknown", and the caller
     * answers 503 until the contract exists.
     *
     * @param request storage entry request, kept for the future dedicated endpoint
     * @return empty while Crop Storage exposes no capacity endpoint
     */
    public Optional<Boolean> checkStorageCapacity(CropStorageEntryRequest request) {
        return Optional.empty();
    }
}
