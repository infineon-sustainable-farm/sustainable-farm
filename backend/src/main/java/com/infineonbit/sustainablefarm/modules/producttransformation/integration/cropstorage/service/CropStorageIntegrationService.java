package com.infineonbit.sustainablefarm.modules.producttransformation.integration.cropstorage.service;

import com.infineonbit.sustainablefarm.modules.producttransformation.integration.cropstorage.dto.CropStorageEntryRequest;
import com.infineonbit.sustainablefarm.modules.producttransformation.integration.cropstorage.dto.CropStorageEntryResponse;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.stereotype.Service;
import org.springframework.web.client.RestTemplate;
import org.springframework.web.client.HttpClientErrorException;

/**
 * Crop Storage Integration Service
 * HTTP-based integration with Crop Storage module for storage entry handoff
 *
 * Contract from Crop Storage team:
 * Convention: snake_case
 * Endpoint: /api/crop-storage/entries (or /api/storage-entries - to be decided)
 * Error handling: 409 on capacity overflow
 * batch_code generated by Crop Storage (B26-01 format)
 *
 * @author Abdoul Ben Fatao SANON
 * @version 1.0.0
 */
@Service
public class CropStorageIntegrationService {

    private final RestTemplate restTemplate;

    @Value("${crop-storage.api.base-url:http://localhost:8080}")
    private String cropStorageApiBaseUrl;

    @Value("${crop-storage.api.endpoint:/api/crop-storage/entries}")
    private String cropStorageApiEndpoint;

    @Autowired
    public CropStorageIntegrationService(RestTemplate restTemplate) {
        this.restTemplate = restTemplate;
    }

    /**
     * Create a storage entry in Crop Storage module
     * Used when batch reaches COMPLETED status and needs to be stored
     *
     * @param request Storage entry request
     * @return Storage entry response with generated batch_code
     * @throws HttpClientErrorException if capacity overflow (409)
     */
    public CropStorageEntryResponse createStorageEntry(CropStorageEntryRequest request) {
        String url = cropStorageApiBaseUrl + cropStorageApiEndpoint;
        ResponseEntity<CropStorageEntryResponse> response = restTemplate.postForEntity(
                url,
                request,
                CropStorageEntryResponse.class
        );
        return response.getBody();
    }

    /**
     * Check if storage entry creation would succeed (capacity check)
     * This is a preliminary check before actual entry creation
     *
     * @param request Storage entry request
     * @return true if capacity available, false otherwise
     */
    public boolean checkStorageCapacity(CropStorageEntryRequest request) {
        try {
            // Try to create entry to check capacity
            // Note: This is a provisional approach. Crop Storage may provide a dedicated capacity check endpoint.
            createStorageEntry(request);
            return true;
        } catch (HttpClientErrorException e) {
            if (e.getStatusCode() == HttpStatus.CONFLICT) {
                // 409 Conflict - capacity overflow
                return false;
            }
            throw e;
        }
    }
}
