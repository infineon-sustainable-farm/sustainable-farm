    ADD CONSTRAINT fk_crop_storage_alert_sensor FOREIGN KEY (sensor_id) REFERENCES sensor(id);
ALTER TABLE ONLY crop_storage_alert
    ADD CONSTRAINT fk_crop_storage_alert_storage_zone FOREIGN KEY (storage_zone_id) REFERENCES storage_zone(id);
