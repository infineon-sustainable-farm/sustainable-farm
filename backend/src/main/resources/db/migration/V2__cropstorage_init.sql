-- V2__cropstorage_init.sql: the tables of the Crop Storage module.
--
-- Crop Storage was an excluded module when V1__baseline.sql was written, so the baseline holds
-- none of its tables. Generated the same way as the baseline: the JPA entities of
-- modules.cropstorage built by Hibernate on PostgreSQL 17 (ddl-auto=create, Flyway off, the
-- cross-module foreign keys of CropStorageForeignKeys added in install mode), dumped with
-- pg_dump --schema-only --no-owner --no-privileges for the 9 tables of the module, then put in
-- order: tables, then primary and unique keys, then foreign keys; in a table: id, created_at,
-- updated_at, then the other columns by name. Unique keys are named uk_<table>_<column> like
-- the baseline (ReadableConstraintNamingStrategy).
--
-- Cross-module foreign keys (ADR 0004): the variety of a batch to the Plants catalogue, its
-- harvest to a Plants harvest record, the inspector of a quality check to a staff person.
-- crop_storage_alert stays in the module until the alerts move to the notification module.
-- No data.
--
-- 9 tables, 13 primary and unique keys, 15 foreign keys.

-- ============================================================================
-- Tables
-- ============================================================================

CREATE TABLE crop_storage_alert (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    batch_id bigint,
    corrective_action character varying(255),
    message character varying(255),
    sensor_id bigint,
    severity character varying(255),
    status character varying(255) NOT NULL,
    storage_zone_id bigint,
    type character varying(255) NOT NULL
);

CREATE TABLE crop_storage_batch (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    batch_code character varying(255) NOT NULL,
    current_quantity_kg numeric(10,2),
    customer_priority integer NOT NULL,
    expected_dispatch_date date,
    expiry_date date,
    harvest_date date,
    harvest_id bigint,
    initial_quantity_kg numeric(10,2) NOT NULL,
    moisture_percent numeric(5,2),
    origin character varying(255),
    packaging_date date,
    processing_date date,
    product_stage character varying(20),
    product_type character varying(20) NOT NULL,
    quality_grade character varying(255),
    status character varying(20) NOT NULL,
    storage_entry_date date,
    storage_zone_id bigint,
    supplier_id bigint,
    value_per_kg_amount numeric(14,2),
    value_per_kg_currency character varying(3),
    variety_key character varying(40),
    version bigint NOT NULL,
    CONSTRAINT crop_storage_batch_customer_priority_check CHECK (customer_priority >= 0),
    CONSTRAINT crop_storage_batch_product_stage_check CHECK (product_stage IN ('FRESH', 'DRIED', 'PACKAGED', 'WASTE', 'RETURNED')),
    CONSTRAINT crop_storage_batch_product_type_check CHECK (product_type IN ('FRESH_MANGO', 'DRIED_MANGO')),
    CONSTRAINT crop_storage_batch_status_check CHECK (status IN ('STORED', 'DISPATCHED')),
    CONSTRAINT crop_storage_batch_value_per_kg_currency_check CHECK (value_per_kg_currency IN ('XOF', 'EUR', 'USD'))
);

CREATE TABLE loss_record (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    batch_id bigint NOT NULL,
    cause character varying(255),
    quantity_kg numeric(12,2) NOT NULL,
    recorded_at timestamp(6) without time zone NOT NULL,
    value_amount numeric(14,2),
    value_currency character varying(3),
    CONSTRAINT loss_record_value_currency_check CHECK (value_currency IN ('XOF', 'EUR', 'USD'))
);

CREATE TABLE quality_check (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    batch_id bigint NOT NULL,
    checked_at timestamp(6) without time zone NOT NULL,
    inspector_person_id bigint,
    moisture_percent numeric(5,2),
    notes character varying(255),
    passed boolean NOT NULL,
    quality_grade character varying(255)
);

CREATE TABLE sensor (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    installation_date date,
    name character varying(255),
    sensor_code character varying(255) NOT NULL,
    sensor_type character varying(255),
    status character varying(20) NOT NULL,
    storage_zone_id bigint,
    CONSTRAINT sensor_status_check CHECK (status IN ('ACTIVE', 'MAINTENANCE', 'INACTIVE'))
);

CREATE TABLE sensor_reading (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    humidity numeric(5,2),
    measured_at timestamp(6) without time zone NOT NULL,
    sensor_id bigint NOT NULL,
    temperature numeric(5,2)
);

CREATE TABLE stock_movement (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    batch_id bigint NOT NULL,
    from_zone_id bigint,
    moved_at timestamp(6) without time zone NOT NULL,
    quantity_kg numeric(12,2) NOT NULL,
    reason character varying(255),
    to_zone_id bigint,
    type character varying(20) NOT NULL,
    CONSTRAINT stock_movement_type_check CHECK (type IN ('IN', 'OUT', 'TRANSFER'))
);

CREATE TABLE storage_zone (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    capacity_kg numeric(12,2) NOT NULL,
    cooling_available boolean,
    description character varying(255),
    humidity_max_percent numeric(5,2),
    humidity_min_percent numeric(5,2),
    name character varying(255),
    status character varying(20) NOT NULL,
    temperature_max_celsius numeric(5,2),
    temperature_min_celsius numeric(5,2),
    zone_code character varying(255) NOT NULL,
    CONSTRAINT storage_zone_status_check CHECK (status IN ('ACTIVE', 'MAINTENANCE', 'INACTIVE'))
);

CREATE TABLE supplier (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    contact_phone character varying(255),
    name character varying(255) NOT NULL,
    region character varying(255),
    supplier_code character varying(255) NOT NULL
);

