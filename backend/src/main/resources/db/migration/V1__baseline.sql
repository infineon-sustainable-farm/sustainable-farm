-- V1__baseline.sql: the whole schema of Sustainable Farm, from the final entity model.
--
-- Generated from the JPA entities (Hibernate on PostgreSQL 17, ddl-auto=create, Flyway off,
-- plus the cross-module foreign keys declared as CrossModuleForeignKey beans, added by
-- CrossModuleForeignKeyInstaller in install mode), dumped with pg_dump --schema-only
-- --no-owner --no-privileges and put in order: tables, then primary and unique keys, then
-- indexes, then foreign keys; inside each part, by module then by table then by name. In a
-- table: id, created_at, updated_at, then the other columns by name. Two differences with what
-- Hibernate builds: the index idx_zone_entity_requirements_zone_entity_id of the excluded
-- sitesecurity module, which its entity does not declare, and the uk_<table>_<column> name
-- (ReadableConstraintNamingStrategy) of the five unique keys of a column declared unique, which
-- PostgreSQL would name <table>_<column>_key.
-- A database built from this file dumps back to the same file.
--
-- It holds no data. The reference data every profile needs (variety catalogue, IoT system
-- person) is written by the loaders at startup; the dev demo data set is seed/demo-data.sql,
-- loaded by core.config.DemoDataSeeder (profile dev).
--
-- It runs on an EMPTY database only (no baseline-on-migrate, docs/adr/0002). The entities
-- must stay equal to it: the application starts with ddl-auto=validate, and
-- CrossModuleForeignKeyInstaller fails the startup when a declared cross-module foreign key
-- is missing. A change to an entity comes with a new migration (V2, V3...), never with an
-- edit of this file once it is applied.
--
-- 99 tables, 145 primary and unique keys, 134 indexes, 117 foreign keys.

