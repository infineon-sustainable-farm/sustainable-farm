import { useEffect, useState } from 'react';
import { CalendarPlus, EllipsisVertical, FileSpreadsheet, FileText, Globe, Map as MapIcon, Pencil, ScanSearch, Trash2, TriangleAlert } from 'lucide-react';
import { useTranslation } from 'react-i18next';
import { Badge, Button, Card, IconButton } from '../../../../shared/ui';
import { resolveCategory, useReportText } from './reportUtils';

// Icon tile of a card, by category, alternating along the grid as before.
const PRESETS = {
  forecasting: [
    { icon: ScanSearch, tone: 'bg-primary-tint text-primary' },
    { icon: Globe, tone: 'bg-info-tint text-info-fg' },
  ],
  regional: [
    { icon: TriangleAlert, tone: 'bg-error-tint text-error-fg' },
    { icon: MapIcon, tone: 'bg-primary-tint text-primary' },
  ],
  risk: [{ icon: TriangleAlert, tone: 'bg-error-tint text-error-fg' }],
};

function isAutoGenerated(report) {
  const generatedBy = (report.generatedBy || '').toLowerCase();
  return Boolean(report.isScheduled) || generatedBy === 'system' || generatedBy === 'auto';
}

function ReportMenu({ report, onEdit, onDelete }) {
  const { t } = useTranslation('salesmarketing');
  const [open, setOpen] = useState(false);

  useEffect(() => {
    if (!open) return undefined;
    const close = () => setOpen(false);
    window.addEventListener('click', close);
    return () => window.removeEventListener('click', close);
  }, [open]);

  return (
    <div className="relative">
      <IconButton
        icon={EllipsisVertical}
        tone="neutral"
        label={t('reports.actionsFor', { title: report.title })}
        aria-expanded={open}
        onClick={(event) => {
          event.stopPropagation();
          setOpen((current) => !current);
        }}
      />
      {open && (
        <div
          onClick={(event) => event.stopPropagation()}
          className="absolute top-full right-0 z-(--z-overlay) mt-1 w-44 rounded-control border border-border-subtle bg-surface-raised py-1 shadow-overlay"
        >
          <button
            type="button"
            onClick={() => {
              setOpen(false);
              onEdit(report.source);
            }}
            className="flex w-full cursor-pointer items-center gap-2 px-3 py-2 text-left text-sm hover:bg-surface-muted"
          >
            <Pencil size={16} aria-hidden="true" className="text-text-muted" />
            {t('reports.editReport')}
          </button>
          <button
            type="button"
            onClick={() => {
              setOpen(false);
              onDelete(report.source);
            }}
            className="flex w-full cursor-pointer items-center gap-2 px-3 py-2 text-left text-sm text-error-fg hover:bg-error-tint"
          >
            <Trash2 size={16} aria-hidden="true" />
            {t('reports.deleteReport')}
          </button>
        </div>
      )}
    </div>
  );
}

/** One report: icon, title, summary, generation date, PDF and CSV exports. */
export function ReportCard({ report, index, onEdit, onDelete, onExportPdf, onExportCsv }) {
  const { t } = useTranslation('salesmarketing');
  const text = useReportText();
  const list = PRESETS[resolveCategory(report.reportType)] || PRESETS.forecasting;
  const { icon: Icon, tone } = list[index % list.length];
  const title = text.title(report);

  return (
    <Card className="flex h-full flex-col">
      <div className="mb-4 flex items-start justify-between">
        <div className={`flex h-12 w-12 items-center justify-center rounded-tile ${tone}`}>
          <Icon size={20} aria-hidden="true" />
        </div>
        {isAutoGenerated(report) ? (
          <Badge tone="neutral">{t('reports.autoGen')}</Badge>
        ) : (
          <ReportMenu report={{ title, source: report }} onEdit={onEdit} onDelete={onDelete} />
        )}
      </div>
      <h3 className="mb-1 text-lg font-semibold">{title}</h3>
      <p className="mb-6 line-clamp-2 text-sm text-text-muted">{text.summary(report)}</p>
      <div className="mt-auto">
        <div className="mb-2 flex items-center justify-between py-2 text-sm">
          <span className="text-xs text-text-muted">{t('reports.generated')}</span>
          <span>{text.period(report)}</span>
        </div>
        <div className="flex gap-2">
          <Button variant="secondary" size="sm" icon={FileText} className="flex-1" onClick={() => onExportPdf(report)}>
            {t('reports.pdf')}
          </Button>
          <Button variant="secondary" size="sm" icon={FileSpreadsheet} className="flex-1" onClick={() => onExportCsv(report)}>
            {t('reports.csv')}
          </Button>
        </div>
      </div>
    </Card>
  );
}

